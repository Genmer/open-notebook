def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def build_agents_block(locale):
    lines = ["  agents: {"]
    for dotted, table in KEYS:
        ns, key = dotted.split(".", 1)
        if ns == "agents":
            lines.append(f'    {key}: "{esc(table[locale])}",')
    lines.append("  },")
    return lines


def build_lines_for(namespace, locale):
    return [
        f'    {key}: "{esc(table[locale])}",'
        for dotted, table in KEYS
        for ns, key in [dotted.split(".", 1)]
        if ns == namespace
    ]


def insert_into_block(lines, block_name, new_lines):
    """Insert new_lines just before the closing line of `  block_name: {`."""
    start = next(i for i, ln in enumerate(lines) if ln.strip() == f"{block_name}: {{")
    # Start one level deep (the block's own opening brace); the closing line
    # is the first line that brings the depth back to zero.
    depth = 1
    for i in range(start + 1, len(lines)):
        s = lines[i]
        depth += s.count("{") - s.count("}")
        if depth == 0 and s.strip().startswith("}"):
            return lines[:i] + new_lines + lines[i:]
    raise RuntimeError(f"closing brace not found for {block_name}")


base = "frontend/src/lib/locales"
for loc in LOCALES:
    path = os.path.join(base, loc, "index.ts")
    with io.open(path, "r", encoding="utf-8") as f:
        text = f.read()
    if "agents: {" in text:
        print(f"skip {loc} (already present)")
        continue
    lines = text.split("\n")

    # 1. single keys into existing navigation + chat blocks
    lines = insert_into_block(lines, "navigation", build_lines_for("navigation", loc))
    lines = insert_into_block(lines, "chat", build_lines_for("chat", loc))

    # 2. new agents namespace before the shape close (satisfies anchor, or
    # en-US's final closing brace)
    anchor = "} satisfies TranslationShape;"
    text = "\n".join(lines)
    idx = text.rfind(anchor)
    if idx == -1:
        close = max(i for i, ln in enumerate(lines) if ln == "}")
        block = build_agents_block(loc)
        lines = lines[:close] + block + lines[close:]
        text = "\n".join(lines)
        print(f"ok {loc} (shape source)")
    else:
        block = "\n".join(build_agents_block(loc)) + "\n"
        text = text[:idx] + block + text[idx:]
        print(f"ok {loc}")

    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
