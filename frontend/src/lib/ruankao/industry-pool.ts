/**
 * hover 多行解释（行业池面板 chip 与 mock 向导行业下拉条目共用；消除两处
 * 重复的 title 表达式）。返回行数组，调用方 `join('\n')` 成原生 title：
 * 行 1 恒为行业名；有 hint 追加业务特征行；有画像再追加三行画像
 * （形态/技术栈/流程，`{{items}}` 为前端 `；` join 后的串）。
 * 无画像条目的行集与无画像功能上线前逐字节一致（降级语义同 hint 空串）。
 */
export function industryTitleLines(entry: IndustryPoolEntry, t: TFunction): string[] {
  const lines: string[] = [entry.name]
  if (entry.hint) lines.push(t('ruankao.industry.hintLine', { hint: entry.hint }))
  const profile = INDUSTRY_PROFILES[entry.name]
  if (profile) {
    lines.push(
      t('ruankao.industry.profileFormsLine', { items: profile.projectForms.join('；') }),
      t('ruankao.industry.profileTechLine', { items: profile.techStack.join('；') }),
      t('ruankao.industry.profileFlowsLine', { items: profile.businessFlows.join('；') }),
    )
  }
  return lines
}
