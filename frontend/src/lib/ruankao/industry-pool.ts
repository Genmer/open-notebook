export function filterIndustryPool(query: string): readonly IndustryPoolEntry[] {
  const q = query.trim()
  if (!q) return INDUSTRY_POOL
  return INDUSTRY_POOL.filter((item) => item.name.includes(q)) // 唯一改动：只按 name 过滤
}


